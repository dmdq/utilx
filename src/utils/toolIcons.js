// 按工具 icon 名解析图标组件，未命中时回退到分类图标，最后回退 FileText
export function resolveToolIcon(iconName, categoryId) {
  if (iconName && toolIconMap[iconName]) return toolIconMap[iconName]
  if (categoryId && categoryIconMap[categoryId]) return categoryIconMap[categoryId]
  return FileText
}
